/** Find which button key a text belongs to, across all languages. */
export function buttonKey(text) {
  for (const L of Object.values(LANGS)) {
    for (const k of ['btn_in', 'btn_out', 'btn_forgot', 'btn_hours', 'btn_lang']) {
      if (L[k] === text) return k;
    }
  }
  return null;
}
